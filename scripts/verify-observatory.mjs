import {chromium} from '@playwright/test';
import {mkdir,writeFile} from 'node:fs/promises';
await mkdir('.artifacts/observatorio',{recursive:true});
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1100}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://127.0.0.1:3127/observatorio',{waitUntil:'networkidle',timeout:90000});
await page.getByLabel('Buscar un lugar de España').waitFor();
await page.waitForFunction(()=>document.querySelectorAll('.ob-map-region').length===19);
await page.locator('.ob-spinning').waitFor({state:'hidden',timeout:90000});
await page.screenshot({path:'.artifacts/observatorio/desktop.png',fullPage:true});
const feed=await page.request.get('http://127.0.0.1:3127/api/observatorio',{timeout:90000});
const data=await feed.json();
await writeFile('.artifacts/observatorio/feed-live.json',JSON.stringify(data,null,2));
console.log(JSON.stringify({status:feed.status(),count:data.stories?.length,sources:data.sources?.map(s=>({id:s.id,state:s.state,count:s.count,latest:s.latest})),errors}));
await page.getByLabel('Comunidad',{exact:true}).selectOption('r-14');
await page.getByLabel('Provincia',{exact:true}).selectOption('p-30');
await page.getByLabel('Municipio',{exact:true}).selectOption('m-30016');
await page.screenshot({path:'.artifacts/observatorio/cartagena.png',fullPage:false});
await page.getByRole('button',{name:'Restablecer filtros',exact:true}).click();
await page.getByLabel('Tu pregunta',{exact:true}).fill('¿Qué novedades hay sobre vivienda?');
await page.getByRole('button',{name:'Lanzar pregunta'}).click();
await page.locator('.ob-answer').waitFor();
console.log('answer',await page.locator('.ob-answer').innerText());
await page.setViewportSize({width:390,height:844});
await page.screenshot({path:'.artifacts/observatorio/mobile.png',fullPage:true});
console.log('mobileOverflow',await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth));
await browser.close();
